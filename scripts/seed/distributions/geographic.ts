interface GeoLocation {
  country: string;
  region: string;
  city: string;
}

interface Location {
  region?: string;
  city: string;
}

interface CountryProfile {
  /** Relative traffic weight (unnormalized). */
  weight: number;
  /** Cities visitors come from; region is an ISO 3166-2 code (without the country prefix). */
  locations: Location[];
  /** BCP 47 language tags visitors from this country typically use. */
  languages?: string[];
}

function loc(city: string, region?: string): Location {
  return { city, region };
}

