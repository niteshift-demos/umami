const countryWeights: WeightedOption<string>[] = Object.entries(countries).map(
  ([value, { weight }]) => ({ value, weight }),
);

export const seededCountryCodes = Object.keys(countries);

export function getRandomGeo(): GeoLocation {
  const country = weightedRandom(countryWeights);
  const { region, city } = pickRandom(countries[country].locations);

  return {
    country,
    // Stored the way the tracker does it: full ISO 3166-2 code, e.g. "US-CA".
    region: region ? `${country}-${region}` : '',
    city,
  };
}

const fallbackLanguages: WeightedOption<string>[] = [
  { value: 'en-US', weight: 0.6 },
  { value: 'en-GB', weight: 0.2 },
  { value: 'es-ES', weight: 0.05 },
  { value: 'fr-FR', weight: 0.05 },
  { value: 'zh-CN', weight: 0.05 },
  { value: 'ar-SA', weight: 0.05 },
];

export function getRandomLanguage(country?: string): string {
  const languages = country ? countries[country]?.languages : undefined;

  if (languages?.length) {
    // Most visitors use a local language; a minority browse in English.
    return Math.random() < 0.9 ? pickRandom(languages) : 'en-US';
  }

  return weightedRandom(fallbackLanguages);
}
